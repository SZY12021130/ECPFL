np.random.seed(RANDOM_SEED)


def build_data_from_real(params_dict):
    """从真实实验数据构建统一的数据结构。
    
    对于缺失数据（None），返回空列表。
    """
    data = {}
    for ds in DATASETS:
        data[ds] = {}
        for method in METHODS:
            y_data = params_dict[ds].get(method)
            if y_data is None:
                # 数据缺失，跳过
                continue
            # 截取到 ROUNDS 长度
            n = len(ROUNDS)
            y = list(y_data)[:n]
            # 如果数据不足 ROUNDS 长度，用最后一个值填充
            while len(y) < n:
                y.append(y[-1] if y else 0.0)
            data[ds][method] = {
                "x": ROUNDS.tolist(),
                "y": y,
            }
    return data


# 构建统一的数据结构
data = build_data_from_real(DATASET_PARAMS)


