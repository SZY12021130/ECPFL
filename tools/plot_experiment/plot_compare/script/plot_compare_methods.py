# 4. 绘图函数（按配色方案绘制一次）
# ---------------------------------------------------------------------------
def _draw_one_theme(theme_name, colors, data, plotter):
    """绘制并保存某一配色方案的对比图。"""
    # 颜色自动补全
    method_colors = list(colors)
    if len(method_colors) < len(METHODS):
        cmap = matplotlib.colormaps["tab10"]
        for i in range(len(method_colors), len(METHODS)):
            method_colors.append(matplotlib.colors.to_hex(cmap(i)))
    color_dict = dict(zip(METHODS, method_colors))

    with plt.style.context(plotter.style):
        fig, axes = plt.subplots(1, len(DATASETS), figsize=(18, 4))
        if len(DATASETS) == 1:
            axes = [axes]

        use_outside = LEGEND_CONFIG.startswith("outside")
        legend_handles = []
        legend_labels = []

        for ax, ds, subtitle, ylim in zip(axes, DATASETS, SUBTITLES, YLIMS):
            for method in METHODS:
                if method not in data[ds]:
                    continue  # 跳过缺失数据
                series = data[ds][method]
                line, = ax.plot(
                    series["x"],
                    series["y"],
                    label=method,
                    color=color_dict[method],
                    linewidth=3.5,
                    marker="o",
                    markersize=2.5,
                    markevery=15,
                )
                if use_outside and ax == axes[0]:
                    legend_handles.append(line)
                    legend_labels.append(method)

            ax.set_xlabel("Number of Rounds", fontsize=FONT_SIZE_LABEL)
            ax.set_ylabel("Test Accuracy (%)", fontsize=FONT_SIZE_LABEL)
            ax.set_title(subtitle, fontsize=FONT_SIZE_TITLE)
            ax.set_xlim(0, 50)
            ax.set_ylim(ylim)
            ax.grid(True, linestyle="--", alpha=0.5)

            # 轴线与刻度线加粗
            for spine in ax.spines.values():
                spine.set_linewidth(SPINE_LW)
            ax.tick_params(axis="both", width=TICK_WIDTH, length=TICK_LENGTH,
                           labelsize=FONT_SIZE_TICK)

            # 子图内部图例
            if not use_outside:
                loc_str = LEGEND_CONFIG.replace("_", " ")
                ax.legend(loc=loc_str, fontsize=FONT_SIZE_LEGEND, frameon=True, ncol=LEGEND_NCOL)

        # 全局图例（图外）
        if use_outside:
            if LEGEND_CONFIG == "outside_bottom_center":
                fig.legend(
                    legend_handles, legend_labels,
                    loc="lower center",
                    ncol=LEGEND_NCOL,
                    bbox_to_anchor=(0.5, -0.02),
                    fontsize=FONT_SIZE_LEGEND,
                    frameon=True,
                )
                plt.tight_layout(rect=[0, 0.06, 1, 1])
            elif LEGEND_CONFIG == "outside_top_center":
                fig.legend(
                    legend_handles, legend_labels,
                    loc="lower center",
                    ncol=LEGEND_NCOL,
                    bbox_to_anchor=(0.5, 1.02),
                    fontsize=FONT_SIZE_LEGEND,
                    frameon=True,
                )
                plt.tight_layout(rect=[0, 0, 1, 0.94])
            else:
                raise ValueError(f"暂不支持的图外位置: {LEGEND_CONFIG}")
        else:
            plt.tight_layout()

        # 保存
        save_dir = plotter.output_dir
        for fmt in ["png", "pdf"]:
            fpath = save_dir / f"method_comparison_{theme_name}.{fmt}"
            kwargs = {"bbox_inches": "tight"}
            if fmt == "png":
                kwargs["dpi"] = plotter.dpi
            plt.savefig(fpath, **kwargs)
            print(f"[Saved] {fpath}")

        plt.close(fig)


